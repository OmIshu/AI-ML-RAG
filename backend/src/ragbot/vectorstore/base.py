"""Storage contract: swap Qdrant for FAISS/pgvector by implementing this."""
from typing import Protocol

from ragbot.core.schemas import Chunk


class VectorStore(Protocol):
    def has_doc(self, doc_id: str) -> bool: ...
    def delete_doc(self, doc_id: str) -> None: ...
    def upsert(self, chunks: list[Chunk], vectors) -> None: ...
    def search(self, vector: list[float], k: int, filename: str | None = None) -> list[dict]: ...
    def stats(self) -> list[dict]: ...
